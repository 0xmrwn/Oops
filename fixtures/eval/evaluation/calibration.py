"""Freeze existing synthetic outputs for judge calibration without generating corrections."""

import hashlib
import tempfile
from collections import Counter, defaultdict, deque
from datetime import datetime, timezone
from pathlib import Path

from .records import ROOT, canonical, digest, lines, load_run, read_json, write_json
from .scoring import generating
from .tasks import raw_text


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def public_stress():
    """Only exact fixture evidence can establish provenance for unmarked old cases."""
    path = ROOT.parent / "corpus/stress.jsonl"
    if sha(path) != "fffac2d0b9ab9b5b99893332b0d7cd6212286c17d98cef389bed0b46acea61f5":
        raise ValueError("Public stress fixtures changed; review their provenance before calibration import.")
    return {c["id"]: c for c in lines(path)}, path


def synthetic_case(case, public):
    if case.get("split") == "held" or case.get("origin") == "real":
        return None
    copied = dict(case)
    if case.get("origin") not in {"synthetic", "injected", "derived"}:
        known = public.get(case["id"])
        if not known or any(case.get(k) != known.get(k) for k in ("input", "expected", "alternatives")):
            raise ValueError("Calibration accepts marked synthetic cases or exact public stress fixtures only.")
        copied["origin"] = "synthetic"
        # These language labels apply only after matching the exact public fixture evidence.
        french = {"04", "05", "06", "10", "20", "28", "31", "35"}
        copied["lang"] = "fr" if case["id"].removeprefix("stress-") in french else "en"
        copied["provenance"] = "Exact public fixtures/corpus/stress.jsonl evidence; no reviewed reference."
    copied["split"] = "dev"
    if not copied.get("length"):
        n = len(copied["input"])
        copied["length"] = "xs" if n < 80 else "s" if n < 250 else "m" if n < 1000 else "l"
    return copied


def select(candidates, cases, limit):
    """Round-robin observable cohorts; this is a coverage panel, not an unbiased estimate."""
    buckets = defaultdict(deque)
    for row in sorted(candidates, key=lambda r: digest(r)):
        case = cases[row["case"]]
        clean = (case.get("tags") or {}).get("clean")
        if clean is None and case.get("expected") is not None:
            clean = case["expected"] == case["input"]
        condition = (
            "raw/reconciled" if raw_text(row) not in {None, row.get("output")} else row.get("verdict", "unknown")
        )
        cohort = (case.get("lang", "unknown"), str(clean), case["length"], condition)
        buckets[cohort].append(row)
    queues, result = [buckets[k] for k in sorted(buckets)], []
    while queues and len(result) < limit:
        for queue in queues:
            if len(result) == limit:
                break
            result.append(queue.popleft())
        queues = [q for q in queues if q]
    return result


def authored_supplement(limit):
    """Deliberately constructed answers supplement history; they are never model measurements."""
    path = ROOT / "cases.jsonl"
    frozen = read_json(ROOT / "dataset.json")
    if sha(path) != frozen["dev"]["sha256"]:
        raise ValueError("The authored supplement requires the reviewed development corpus freeze.")
    available, chosen = lines(path), []
    for language, clean in [("fr", False), ("mixed", False), ("fr", True), ("mixed", True), ("en", True)]:
        match = next(
            (
                c
                for c in available
                if c.get("lang") == language
                and (c["expected"] == c["input"]) == clean
                and c["split"] == "dev"
                and c["id"] not in {x["id"] for x in chosen}
            ),
            None,
        )
        if match:
            chosen.append(match)
    cases, rows = {}, []
    for case in chosen:
        if len(rows) >= limit:
            break
        cases[case["id"]] = case
        wrong = case["input"] if case["expected"] != case["input"] else case["expected"] + " I agree with this message."
        for attempt, output in enumerate([case["expected"], wrong], 1):
            if len(rows) >= limit:
                break
            rows.append(
                {
                    "case": case["id"],
                    "attempt": attempt,
                    "output": output,
                    "raw": canonical({"text": output}),
                    "verdict": "authored",
                    "provider": "authored",
                    "lane": "fixture",
                    "model": "authored-counterexample",
                    "calibration_origin": "authored-correct-or-counterexample; not generated by any model",
                    "file": "authored",
                }
            )
    return (
        cases,
        rows,
        {
            "path": str(path),
            "sha256": sha(path),
            "construction": "Approved expected answer; unchanged error or deliberately appended semantic addition. Owner output labels are still required.",
        },
    )


def prepare_calibration(source, out_root, out_run, limit=30):
    source, out_root = Path(source).resolve(), Path(out_root).expanduser().resolve()
    if not out_run or Path(out_run).name != out_run or out_run in {".", ".."} or "\\" in out_run:
        raise ValueError("Output run must be a folder name, not a path.")
    if limit <= 0:
        raise ValueError("--limit must be positive.")
    destination = out_root / out_run
    if destination.resolve().parent != out_root or destination.resolve() == source:
        raise ValueError("Calibration needs a separate output run under the selected runs directory.")
    if generating(source):
        raise ValueError("Wait for source generation to stop before freezing a calibration panel.")
    experiment, manifest, cases, records = load_run(source)
    if experiment and experiment.get("kind") == "calibration":
        raise ValueError("Choose an original generation run, not another calibration panel.")
    public, public_path = public_stress()
    eligible_cases = {}
    for identifier, case in cases.items():
        copied = synthetic_case(case, public)
        if copied is not None:
            eligible_cases[identifier] = copied
    candidates, seen = [], set()
    for row in records:
        if row["case"] not in eligible_cases:
            continue
        output, raw = row.get("output"), raw_text(row)
        if output is None and raw is None:
            continue  # Operational failures have no candidate text for quality calibration.
        identity = (row["case"], output, raw)
        if identity not in seen:
            candidates.append(row)
            seen.add(identity)
    supplement_cases, supplement, supplement_provenance = authored_supplement(min(10, limit // 3))
    history = select(candidates, eligible_cases, limit - len(supplement))
    if not history:
        raise ValueError("No eligible synthetic candidate answers remain after excluding held-back/private cases.")
    selected = history + supplement
    eligible_cases.update(supplement_cases)
    identifiers = {r["case"] for r in selected}
    selected_cases = [eligible_cases[k] for k in sorted(identifiers)]
    paths = [source / "manifest.json", *(source / f for f in sorted({r["file"] for r in history}))]
    source_cases = source / "cases.jsonl"
    paths.append(source_cases if source_cases.exists() else Path(manifest["cases"]).expanduser())
    provenance = {
        "kind": "historical-model-outputs",
        "source_run": source.name,
        "source_files": {str(p): sha(p) for p in paths},
        "public_fixture_sha256": sha(public_path),
        "source_prompt_version": manifest.get("prompt", "unknown"),
        "source_experiment": experiment,
        "authored_supplement": supplement_provenance,
        "selection": "Deterministic cohort round-robin over distinct case/output/raw combinations; not representative sampling.",
        "records": [
            {
                "file": r["file"],
                "case": r["case"],
                "attempt": r["attempt"],
                "record_sha256": digest({k: v for k, v in r.items() if k != "file"}),
            }
            for r in selected
        ],
    }
    identity = digest({"provenance": provenance, "limit": limit})
    if destination.exists():
        previous = read_json(destination / "experiment.json")
        if previous.get("kind") != "calibration" or previous.get("preparation_sha256") != identity:
            raise ValueError("Output run already contains a different panel; choose a new --out-run.")
        load_run(destination)
        return {"run": out_run, "out": str(destination), "unchanged": True, "generation_started": False}
    out_root.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".calibration-", dir=out_root) as temporary:
        directory = Path(temporary) / "panel"
        directory.mkdir(mode=0o700)
        (directory / "results").mkdir(mode=0o700)
        case_file = directory / "cases.jsonl"
        case_file.write_text("".join(canonical(c) + "\n" for c in selected_cases))
        case_file.chmod(0o600)
        grouped = defaultdict(list)
        for row in selected:
            copied = {k: v for k, v in row.items() if k != "file"}
            if row["file"] != "authored":
                copied["source_run"] = copied.pop("run", source.name)
            copied["run"] = out_run
            grouped[row["file"]].append(copied)
        lanes = []
        for index, lane in enumerate(manifest["lanes"]):
            if lane["file"] not in grouped:
                continue
            file = f"results/calibration--{index}.jsonl"
            target = directory / file
            target.write_text("".join(canonical(row) + "\n" for row in grouped[lane["file"]]))
            target.chmod(0o600)
            lanes.append({**lane, "file": file, "records": len(grouped[lane["file"]]), "state": "done", "deferred": 0})
        if supplement:
            file = "results/authored.jsonl"
            (directory / file).write_text("".join(canonical(row) + "\n" for row in grouped["authored"]))
            (directory / file).chmod(0o600)
            lanes.append(
                {
                    "file": file,
                    "lane": "fixture",
                    "provider": "authored",
                    "model": "authored-counterexample",
                    "resolved": "authored-counterexample",
                    "records": len(supplement),
                    "state": "done",
                }
            )
        now = datetime.now(timezone.utc).isoformat()
        config = {"kind": "calibration", "source_run": source.name, "limit": limit}
        write_json(directory / "config.json", config)
        write_json(directory / "provenance.json", provenance)
        write_json(
            directory / "manifest.json",
            {
                "run": out_run,
                "kind": "calibration",
                "cases": str(destination / "cases.jsonl"),
                "attempts": max(manifest["attempts"], 2 if supplement else 1),
                "created": now,
                "updated": now,
                "prompt": manifest.get("prompt", "unknown"),
                "lanes": lanes,
            },
        )
        snapshot_names = [
            "cases.jsonl",
            "config.json",
            "provenance.json",
            "manifest.json",
            *[lane["file"] for lane in lanes],
        ]
        write_json(
            directory / "experiment.json",
            {
                "schema_version": 2,
                "kind": "calibration",
                "preparation_sha256": identity,
                "snapshots": {name: sha(directory / name) for name in snapshot_names},
                "generation_started": False,
                "notice": "Historical output calibration panel, not a baseline or a reconstructed generation experiment.",
            },
        )
        directory.rename(destination)
    coverage = {
        dimension: dict(Counter(c.get(dimension, "unknown") for c in selected_cases))
        for dimension in ("lang", "length", "origin")
    }
    return {
        "run": out_run,
        "out": str(destination),
        "selected_records": len(selected),
        "cases": len(selected_cases),
        "historical_records": len(history),
        "authored_records": len(supplement),
        "coverage": coverage,
        "missing_references": sum(c.get("expected") is None for c in selected_cases),
        "generation_started": False,
        "judging_started": False,
        "remaining": "Blind owner labels, explicit judge execution, validation and any missing cohort coverage are still required.",
    }
